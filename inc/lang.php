function t(string $key, ?string $fallback = null): string
{
    $lang = current_lang();
    $dict = translations();
    return $dict[$lang][$key] ?? $dict['id'][$key] ?? $fallback ?? $key;
}

/**
 * Label kategori yang ramah untuk tampilan.
 */
function category_label(string $cat): string
{
    return $cat === 'AI/Data' ? (is_en() ? 'AI / Data' : 'AI / Data') : $cat;
}
